import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import { toast } from 'sonner';
import { Check, CheckCircle2, Coins, Copy, Gift, Loader2, Mail, MessageCircle, Play, QrCode, Share2, UserCheck, XCircle } from 'lucide-react';
import { Card, CardContent } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import QRCodeDisplay from '@/components/referral/QRCodeDisplay';
import ReferralAckPanel from '@/components/referral/ReferralAckPanel';
import {
  referralRpc, rpcMessage, useInvalidateReferral, useMyReferralInvite, useReferralOverview,
} from '@/hooks/useReferralProgram';
import {
  deviceId, formatRate, normalizeReferralCode, referralLink, referStepExample, shareMessage, shareUrl, type ShareChannel,
} from '@/lib/referrals';

type Pending = { channel: ShareChannel | 'qr' } | null;

/**
 * Feature Z onboarding step "Refer & earn": explains the programme with the real settings, shows the consultant's own
 * code (generated by the database when the step opens) and lets them add who invited them. Never mandatory; the terms
 * acknowledgement is asked only when they press Share (or open the Refer & earn page).
 */
export default function ReferEarnStep({ onDone, onLater }: { onDone?: () => void; onLater?: () => void }) {
  const { t, i18n } = useTranslation();
  const lang: 'en' | 'ar' = i18n.language?.startsWith('ar') ? 'ar' : 'en';
  const overview = useReferralOverview(true);
  const invite = useMyReferralInvite(true);
  const invalidate = useInvalidateReferral();
  const [copied, setCopied] = useState(false);
  const [pending, setPending] = useState<Pending>(null);
  const [showQR, setShowQR] = useState(false);
  const ov = overview.data?.data ?? null;

  if (!overview.data?.available || !ov || !ov.settings.enabled) return null;
  const s = ov.settings;
  const rate = formatRate(s.rate_percent);
  const usd = (v: number) => new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US', { style: 'currency', currency: 'USD' }).format(v);
  const ex = referStepExample(s.rate_percent);
  const link = referralLink(ov.code);
  const msg = shareMessage(lang, { code: ov.code, link, rate: s.rate_percent, months: s.months });

  const copy = async () => {
    try { await navigator.clipboard.writeText(ov.code); } catch { toast.error(t('refz.copy_failed', 'Copy did not work. Select the text and copy it yourself.')); return; }
    setCopied(true); setTimeout(() => setCopied(false), 1800);
  };
  const doShare = (c: ShareChannel | 'qr') => {
    if (c === 'qr') { setShowQR(true); return; }
    window.open(shareUrl(c, link, msg.text, msg.subject), c === 'email' ? '_self' : '_blank', 'noopener');
  };
  // Share: interview passed (activation rule) -> terms acknowledged (asked here, first time) -> share.
  const share = (c: ShareChannel | 'qr') => {
    if (!ov.activation.interview_passed || !ov.activation.acknowledged) { setPending({ channel: c }); return; }
    doShare(c);
  };

  return (
    <Card className="rounded-2xl" id="refer-earn">
      <CardContent className="p-5 md:p-6 space-y-6">
        <div className="flex flex-wrap items-start justify-between gap-2">
          <div>
            <p className="text-xs font-semibold uppercase tracking-wide text-primary flex items-center gap-1"><Gift className="w-3.5 h-3.5" aria-hidden />{t('refz.title', 'Refer & earn')}</p>
            <h2 className="mt-1 text-xl font-bold text-foreground">{t('refz.step_headline', 'Bring colleagues, earn together')}</h2>
          </div>
          <Badge variant="outline" className="text-[10px]">{t('refz.step_optional', 'Optional - does not affect your profile')}</Badge>
        </div>

        {/* 2. How it works */}
        <ol className="grid gap-3 sm:grid-cols-3">
          {([
            [Share2, t('refz.step_how_1', 'Share your personal code or link')],
            [UserCheck, t('refz.step_how_2', 'Your colleague registers with it and gets verified')],
            [Coins, t('refz.step_how_3', 'You earn {{rate}} % of their fee for every man-day they work for {{months}} months - paid by AI Support 360, never deducted from them', { rate, months: s.months })],
          ] as Array<[typeof Share2, string]>).map(([Icon, text], i) => (
            <li key={i} className="rounded-xl border border-border/60 bg-muted/30 p-4">
              <span className="flex items-center gap-2 text-xs font-semibold text-primary">
                <span className="flex h-6 w-6 items-center justify-center rounded-full bg-primary/10">{i + 1}</span><Icon className="w-4 h-4" aria-hidden />
              </span>
              <p className="mt-2 text-sm text-foreground">{text}</p>
            </li>
          ))}
        </ol>
        <p className="text-xs text-muted-foreground">{t('refz.step_activation', 'Your referral becomes active when you both pass the AI interview (score at least {{pass}}).', { pass: ov.activation.pass_mark })}</p>

        {/* 3. Illustrative example */}
        <section aria-labelledby="refstep-ex" className="rounded-xl bg-primary/5 p-4 space-y-1.5">
          <h3 id="refstep-ex" className="text-sm font-semibold">{t('refz.step_example_title', 'What you could earn')} <Badge variant="outline" className="ms-1 text-[10px]">{t('refz.step_illustrative', 'Illustrative example')}</Badge></h3>
          <p className="text-sm" dir="auto">
            {t('refz.step_example_one', '1 colleague billing {{days}} man-days in a month at {{hourly}}/h: {{days}} x {{hours}} h x {{hourly}} = {{fee}} fee -> your reward {{reward}}.', {
              days: ex.manDays, hours: ex.hours, hourly: usd(ex.hourlyRate), fee: usd(ex.fee), reward: usd(ex.one) })}
          </p>
          <p className="text-sm">{t('refz.step_example_many', '{{n}} colleagues like that -> {{reward}} in that month.', { n: ex.colleagues, reward: usd(ex.many) })}</p>
          <p className="text-[11px] text-muted-foreground">{t('refz.step_example_note', 'Example only, not a promise; rewards depend on your colleagues\' approved and paid work.')}</p>
        </section>

        {/* 4. How you get paid + 5. rules */}
        <div className="grid gap-4 md:grid-cols-2">
          <section aria-labelledby="refstep-paid">
            <h3 id="refstep-paid" className="text-sm font-semibold">{t('refz.step_paid_title', 'How you get paid')}</h3>
            <ul className="mt-2 list-disc ps-5 space-y-1 text-sm text-muted-foreground">
              <li>{t('refz.step_paid_1', 'A reward line appears after the client pays.')}</li>
              <li>{t('refz.step_paid_2', 'It becomes available when your colleague\'s payout is released.')}</li>
              <li>{t('refz.step_paid_3', 'It is paid with your normal payout once your available amount reaches {{min}}.', { min: usd(s.min_payout) })}</li>
              <li>{t('refz.step_paid_4', 'You see every line on your Earnings and Referral calculations pages.')}</li>
            </ul>
          </section>
          <section aria-labelledby="refstep-rules">
            <h3 id="refstep-rules" className="text-sm font-semibold">{t('refz.step_rules_title', 'The rules')}</h3>
            <ul className="mt-2 list-disc ps-5 space-y-1 text-sm text-muted-foreground">
              <li>{t('refz.step_rule_1', 'Verified colleagues only.')}</li>
              <li>{t('refz.step_rule_2', 'No self-referral.')}</li>
              <li>{t('refz.step_rule_3', 'Rewards reverse if a payment is refunded.')}</li>
              <li><Link to="/referral-terms" target="_blank" rel="noopener" className="text-primary underline">{t('refz.terms_link', 'referral programme terms')}</Link></li>
              <li>{t('refz.step_rule_tax', 'Tax on rewards is your responsibility.')} <Badge variant="outline" className="ms-1 text-[10px]">{t('refz.draft', 'Draft')}</Badge></li>
            </ul>
          </section>
        </div>

        {/* 6. Own code + share */}
        <section aria-labelledby="refstep-code" className="space-y-3">
          <h3 id="refstep-code" className="text-sm font-semibold">{t('refz.step_code_title', 'Your personal code')}</h3>
          <div className="flex flex-wrap items-center gap-2">
            <span dir="ltr" className="rounded-xl border border-border bg-muted/40 px-4 py-2 font-mono text-lg font-semibold tracking-wide">{ov.code}</span>
            <Button variant="outline" size="sm" className="rounded-xl" onClick={copy}>{copied ? <Check className="w-4 h-4 me-1" /> : <Copy className="w-4 h-4 me-1" />}{t('refz.copy', 'Copy')}</Button>
            {([['whatsapp', 'WhatsApp', MessageCircle], ['linkedin', 'LinkedIn', Share2], ['email', t('refz.email', 'E-mail'), Mail], ['qr', t('refz.qr', 'QR code'), QrCode]] as Array<[ShareChannel | 'qr', string, typeof Share2]>).map(([c, label, Icon]) => (
              <Button key={c} variant="outline" size="sm" className="rounded-xl" onClick={() => share(c)} disabled={ov.disabled}><Icon className="w-4 h-4 me-1" />{label}</Button>
            ))}
          </div>
          {pending && !ov.activation.interview_passed && (
            <div role="status" className="rounded-xl border border-warning/40 bg-warning/5 p-3 text-sm space-y-2">
              <p>{t('refz.share_needs_interview', 'Sharing starts after you pass the AI interview (score at least {{pass}}). Your code is already saved.', { pass: ov.activation.pass_mark })}</p>
              <Button asChild size="sm" className="rounded-xl"><Link to="/consultant/interviews?start=1"><Play className="me-1 h-4 w-4" />{t('refz.start_interview', 'Start AI interview')}</Link></Button>
            </div>
          )}
          {pending && ov.activation.interview_passed && !ov.activation.acknowledged && (
            <div className="rounded-xl border border-primary/30 p-3">
              <ReferralAckPanel version={s.terms_version} rate={s.rate_percent} months={s.months} passMark={ov.activation.pass_mark} source="share"
                onDone={() => { const c = pending.channel; setPending(null); invalidate(); doShare(c); }} />
            </div>
          )}
          {showQR && <QRCodeDisplay url={link} />}
        </section>

        {/* 6b. Who invited you? */}
        {invite.isFetched && !invite.data && <WhoInvited onLinked={invalidate} />}

        {/* 7. Skippable */}
        <div className="flex flex-wrap justify-end gap-2 border-t border-border/60 pt-4">
          {onLater && <Button variant="ghost" onClick={onLater}>{t('refz.step_later', 'Maybe later')}</Button>}
          {onDone && <Button onClick={onDone}>{t('refz.step_done', 'Got it')}</Button>}
        </div>
      </CardContent>
    </Card>
  );
}

function WhoInvited({ onLinked }: { onLinked: () => void }) {
  const { t } = useTranslation();
  const [value, setValue] = useState('');
  const [check, setCheck] = useState<{ state: 'idle' | 'checking' | 'valid' | 'invalid' | 'error'; name?: string }>({ state: 'idle' });
  const [busy, setBusy] = useState(false);
  const [result, setResult] = useState<string | null>(null);
  const code = normalizeReferralCode(value);

  useEffect(() => {
    if (code.length < 4) { setCheck({ state: 'idle' }); return; }
    let live = true;
    setCheck({ state: 'checking' });
    const id = setTimeout(async () => {
      const { data, error } = await referralRpc('referral_validate_code', { _code: code });
      if (!live) return;
      if (error) { setCheck({ state: 'error' }); return; }
      const o = (data ?? {}) as { valid?: boolean; name?: string };
      setCheck(o.valid ? { state: 'valid', name: o.name } : { state: 'invalid' });
    }, 450);
    return () => { live = false; clearTimeout(id); };
  }, [code]);

  const link = async () => {
    setBusy(true);
    const { data, error } = await referralRpc('referral_claim', { _code: code, _device: deviceId() || null });
    setBusy(false);
    if (error) { toast.error(rpcMessage(error, t('refz.claim_failed', 'The code could not be added.'))); return; }
    const r = String((data as { result?: string } | null)?.result ?? '');
    setResult(r);
    if (r === 'ok') { toast.success(t('refz.claimed', 'Your referral code is linked. You were referred by {{name}}.', { name: check.name ?? '' })); onLinked(); }
  };

  const message: Record<string, string> = {
    too_late: t('refz.claim_too_late', 'A code can only be added in the first days after sign-up and before your first paid ticket.'),
    self: t('refz.claim_self', 'You can not use your own code.'),
    loop: t('refz.claim_loop', 'This code can not be used (you referred this consultant).'),
    invalid: t('refz.code_unknown', 'This code was not found. Check it or leave the field empty.'),
    already: t('refz.claim_already', 'A referral code is already linked to your account.'),
    off: t('refz.paused', 'The referral programme is paused at the moment. Rewards already earned stay yours.'),
  };

  return (
    <section aria-labelledby="refstep-who" className="space-y-2 rounded-xl border border-border/60 p-4">
      <h3 id="refstep-who" className="text-sm font-semibold">{t('refz.who_title', 'Who invited you? Enter a referral code')}</h3>
      <p className="text-xs text-muted-foreground">{t('refz.who_hint', 'Optional. Once linked it can not be changed.')}</p>
      <div className="flex flex-wrap gap-2">
        <Label htmlFor="refstep-who-code" className="sr-only">{t('refz.signup_label', 'Referral code (optional)')}</Label>
        <Input id="refstep-who-code" dir="ltr" value={value} maxLength={24} onChange={(e) => setValue(e.target.value.toUpperCase())} placeholder="SAP-NAME-7K2"
          className="max-w-xs font-mono rounded-xl" aria-describedby="refstep-who-status" disabled={result === 'ok'} />
        <Button onClick={link} disabled={check.state !== 'valid' || busy || result === 'ok'} className="rounded-xl">
          {busy && <Loader2 className="w-4 h-4 me-2 animate-spin" />}{t('refz.who_link', 'Link this code')}
        </Button>
      </div>
      <p id="refstep-who-status" aria-live="polite" className="min-h-[1rem] text-xs">
        {check.state === 'checking' && <span className="text-muted-foreground">{t('refz.checking', 'Checking...')}</span>}
        {check.state === 'valid' && result !== 'ok' && <span className="inline-flex items-center gap-1 text-success"><CheckCircle2 className="w-3 h-3" />{t('refz.code_belongs', 'Code belongs to {{name}}', { name: check.name ?? '' })}</span>}
        {check.state === 'invalid' && <span className="inline-flex items-center gap-1 text-destructive"><XCircle className="w-3 h-3" />{message.invalid}</span>}
        {result && result !== 'ok' && <span className="text-destructive">{message[result] ?? message.invalid}</span>}
        {result === 'ok' && <span className="text-success">{t('refz.claimed', 'Your referral code is linked. You were referred by {{name}}.', { name: check.name ?? '' })}</span>}
      </p>
    </section>
  );
}
