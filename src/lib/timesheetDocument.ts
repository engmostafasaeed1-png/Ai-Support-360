import type { ExportRow } from './timesheetExport';

export const TABLE_COLUMNS = ['#', 'Date', 'Activity / description', 'Start', 'End', 'Hours', 'Amount', 'Status'];
export const TIMESHEET_DISCLAIMER = 'Generated by AI Support 360. The platform only connects clients and consultants and is not a party to the engagement.';
export const ARABIC_TEXT = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/;

/** Helvetica output is deliberately ASCII-only; Arabic is sent to browser printing instead. */
export function asciiText(text: string): string {
  return text.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[–—]/g, '-').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7e\n]/g, '?');
}

export function exportStatus(status: string): string {
  if (/^(signed|approved)$/i.test(status)) return 'Approved';
  if (/^(submitted|waiting for approval)$/i.test(status)) return 'Submitted';
  if (/^(changes_requested|changes requested)$/i.test(status)) return 'Changes requested';
  return 'Draft';
}

export interface DocumentRow {
  kind: 'entry' | 'subtotal' | 'total';
  cells: string[];
  hours: number;
  amount: number | null;
}

export function rowTotals(rows: ExportRow[]): { hours: number; amount: number } {
  const round = (value: number) => Math.round((value + Number.EPSILON) * 100) / 100;
  return { hours: round(rows.reduce((sum, r) => sum + r.hours, 0)), amount: round(rows.reduce((sum, r) => sum + (r.amount ?? 0), 0)) };
}

export function activityText(row: ExportRow): string {
  return `${row.description || '-'}\n${row.category} | ${row.consultant} | ${row.billable ? 'Billable' : 'Not billable'} | Rate: ${row.rate == null ? 'pending' : row.rate.toFixed(2)} ${row.currency}`;
}

export function buildDocumentRows(rows: ExportRow[], groupByDay = false): DocumentRow[] {
  const ordered = groupByDay ? [...rows].sort((a, b) => b.date.localeCompare(a.date)) : rows;
  const result: DocumentRow[] = [];
  const totalRow = (kind: 'subtotal' | 'total', label: string, items: ExportRow[]): DocumentRow => {
    const total = rowTotals(items);
    return { kind, ...total, cells: ['', '', label, '', '', total.hours.toFixed(2), total.amount.toFixed(2), ''] };
  };
  ordered.forEach((r, index) => {
    result.push({ kind: 'entry', hours: r.hours, amount: r.amount, cells: [String(index + 1), r.date.slice(0, 10), activityText(r), r.start || '-', r.end || '-', r.hours.toFixed(2), r.amount == null ? 'Pending' : r.amount.toFixed(2), exportStatus(r.timesheet)] });
    if (groupByDay && ordered[index + 1]?.date !== r.date) {
      const day = ordered.filter(item => item.date === r.date);
      if (day.length > 1) result.push(totalRow('subtotal', `Day subtotal: ${r.date}`, day));
    }
  });
  result.push(totalRow('total', 'TOTAL', rows));
  return result;
}

/** Preserve at most three measured lines, making the omission visible with an ASCII ellipsis. */
export function truncateLines(lines: string[], maxLines = 3, maxWidth = Infinity, measure: (text: string) => number = text => text.length): string[] {
  if (lines.length <= maxLines) return lines;
  const kept = lines.slice(0, maxLines);
  let last = kept[maxLines - 1] ?? '';
  while (last && measure(`${last}...`) > maxWidth) last = last.slice(0, -1);
  kept[maxLines - 1] = `${last.trimEnd()}...`;
  return kept;
}

export function tableRowHeight(lineCounts: number[]): number {
  return Math.max(8, Math.max(1, ...lineCounts) * 4 + 2); // 1 mm padding, 4 mm leading
}

export function needsPageBreak(y: number, height: number, bottom = 270): boolean {
  return y + height > bottom;
}